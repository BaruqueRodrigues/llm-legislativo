suppressPackageStartupMessages(library(testthat))
repo_root <- getwd()
while (!file.exists(file.path(repo_root,"AGENTS.md")) && repo_root!=dirname(repo_root)) repo_root <- dirname(repo_root)
source(file.path(repo_root,"R/download/validator.R"))
source(file.path(repo_root,"R/inventory/common/hashing.R"))
source(file.path(repo_root,"R/inventory/common/storage.R"))
source(file.path(repo_root,"R/download/blob_store.R"))
source(file.path(repo_root,"R/download/camara_annual_csv.R"))

test_that("fila contínua repõe vagas, respeita teto, resolve META e agenda Retry-After", {
  root <- tempfile("scheduler_http_"); dir.create(root); root <- normalizePath(root)
  old_root <- Sys.getenv("DATA_ROOT"); Sys.setenv(DATA_ROOT=root)
  on.exit({Sys.setenv(DATA_ROOT=old_root);unlink(root,recursive=TRUE)},add=TRUE)
  script <- file.path(repo_root,"tests/download/fixture_http_server.py")
  command <- sprintf("python3 %s %s > %s 2>&1 & echo $!",shQuote(script),shQuote(root),shQuote(file.path(root,"server.log")))
  pid <- as.integer(system(command,intern=TRUE))
  on.exit(tools::pskill(pid),add=TRUE)
  for (i in 1:100) { if (file.exists(file.path(root,"port"))) break; Sys.sleep(.05) }
  expect_true(file.exists(file.path(root,"port")))
  base <- paste0("http://127.0.0.1:",readLines(file.path(root,"port"),warn=FALSE))
  urls <- paste0(base,c("/slow","/fast1","/fast2","/meta","/html","/retry","/range"))
  out <- file.path(root,"stage"); dir.create(file.path(out,"document_parts"),recursive=TRUE)
  partial <- file.path(out,"document_parts",paste0(hash_string(urls[[7]]),".part"))
  writeBin(charToRaw("%PDF-1.7"),partial)
  cache <- new.env(parent=emptyenv()); results <- list()
  complete <- function(url,fetched) {
    result <- camara_document_result(fetched,root)
    results[[url]] <<- result
    assign(hash_string(url),result,envir=cache)
  }
  fetch_camara_document_urls_parallel(urls,2024,out,2L,curl::new_pool(total_con=2,host_con=2),cache,complete)
  expect_equal(results[[urls[[4]]]]$status,"verified")
  expect_match(results[[urls[[4]]]]$resolved_url,"/final$")
  expect_equal(results[[urls[[5]]]]$status,"html_error")
  expect_equal(results[[urls[[6]]]]$status,"verified")
  expect_equal(results[[urls[[6]]]]$attempt_count,2L)
  expect_equal(results[[urls[[7]]]]$status,"verified")
  events <- lapply(readLines(file.path(root,"events.jsonl")),jsonlite::fromJSON)
  start <- function(path) vapply(Filter(function(e) e$path==path && e$event=="start",events),`[[`,numeric(1),"at")
  end <- function(path) vapply(Filter(function(e) e$path==path && e$event=="end",events),`[[`,numeric(1),"at")
  expect_lt(start("/fast2"),end("/slow"))
  expect_gte(diff(start("/retry")),1)
  expect_lte(max(vapply(events,`[[`,numeric(1),"active")),2)
  slots <- list.dirs(file.path(root,"staging","download_host_slots"),recursive=TRUE)
  expect_false(any(grepl("slot_[0-9]+$",slots)))
})
